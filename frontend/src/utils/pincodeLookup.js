/**
 * Instantly resolve 6-digit Indian PIN code to district and state.
 */
export function quickLookupPincode(pin) {
  const clean = String(pin || '').replace(/\D/g, '').slice(0, 6);
  if (clean.length !== 6 || !/^[1-9][0-9]{5}$/.test(clean)) {
    return null;
  }

  for (const len of [6, 5, 4, 3, 2]) {
    const prefix = clean.slice(0, len);
    if (PIN_PREFIX_MAP[prefix]) {
      return {
        pincode: clean,
        district: PIN_PREFIX_MAP[prefix].district,
        state: PIN_PREFIX_MAP[prefix].state,
      };
    }
  }

  return null;
}
