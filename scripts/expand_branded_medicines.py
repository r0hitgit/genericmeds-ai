def expand_and_seed_branded_medicines():
    init_db()
    db = SessionLocal()
    df_new = pd.DataFrame(ADDITIONAL_BRANDED_MEDICINES)
    
    # Append to branded_medicines_sample.csv
    csv_path = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "data", "imports", "branded_medicines_sample.csv"))
    if os.path.exists(csv_path):
        df_old = pd.read_csv(csv_path)
        # Avoid duplicate brand_name
        existing_brands = set(df_old["brand_name"].str.lower())
        df_to_add = df_new[~df_new["brand_name"].str.lower().isin(existing_brands)]
        if not df_to_add.empty:
            df_combined = pd.concat([df_old, df_to_add], ignore_index=True)
            df_combined.to_csv(csv_path, index=False)
            print(f"Appended {len(df_to_add)} new branded medicines to {csv_path}")
    else:
        df_new.to_csv(csv_path, index=False)

    # Ingest into database
    report = DataIngestionService.ingest_catalog_dataframe(
        db=db,
        df=df_new,
        source_name="Verified Branded Market Retail",
        source_url="https://nppaipdms.gov.in/NPPA/PharmaSahiDaam/searchMedicine",
    )
    print("Branded Medicine Ingestion Report:")
    print(f"  Processed: {report.records_processed}")
    print(f"  Created:   {report.records_created}")
    print(f"  Updated:   {report.records_updated}")
    print(f"  Errors:    {len(report.validation_errors)}")
    db.close()


if __name__ == "__main__":
    expand_and_seed_branded_medicines()
